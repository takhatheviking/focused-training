const form = document.getElementById('apply-form');
const btn = document.getElementById('btn-submit');
const modal = document.getElementById('modal-success');
const toast = document.getElementById('toast');
const consentEl = document.getElementById('f-consent');

function showToast(message) {
  toast.textContent = message;
  toast.classList.add('is-visible');
  setTimeout(() => toast.classList.remove('is-visible'), 4500);
}

function openModal() { modal.classList.add('is-open'); }
function closeModal() { modal.classList.remove('is-open'); }

document.getElementById('modal-close').addEventListener('click', () => {
  closeModal();
  form.reset();
});
modal.addEventListener('click', (e) => {
  if (e.target === modal) { closeModal(); form.reset(); }
});

form.addEventListener('submit', async (e) => {
  e.preventDefault();

  const requiredFields = form.querySelectorAll('.field[data-field]');
  let allValid = true;
  requiredFields.forEach(field => {
    if (!validateField(field)) allValid = false;
  });

  if (!consentEl.checked) {
    allValid = false;
    showToast(I18N[currentLang]['err.consent']);
  }

  if (!allValid) {
    const firstInvalid = form.querySelector('.field--invalid');
    if (firstInvalid) firstInvalid.scrollIntoView({ behavior: 'smooth', block: 'center' });
    return;
  }

  const url = window.FOCUSED_CONFIG && window.FOCUSED_CONFIG.GAS_URL;
  if (!url || url.includes('PASTE_YOUR')) {
    showToast(I18N[currentLang]['err.config']);
    return;
  }

  const formData = new FormData(form);
  const payload = {
    submittedAt: new Date().toISOString(),
    lang: currentLang.toUpperCase(),
    event: 'Moliyaviy Savodxonlik · 11-okt-2026',
    name: (formData.get('name') || '').trim(),
    phone: (formData.get('phone') || '').trim(),
    channel: formData.get('channel') || '',
    source: formData.get('source') || '',
    pain: (formData.get('pain') || '').trim(),
    userAgent: navigator.userAgent.substring(0, 200),
    referrer: document.referrer || 'direct',
    utm_source: new URLSearchParams(location.search).get('utm_source') || '',
    utm_medium: new URLSearchParams(location.search).get('utm_medium') || '',
    utm_campaign: new URLSearchParams(location.search).get('utm_campaign') || ''
  };

  btn.classList.add('is-loading');
  btn.disabled = true;

  try {
    const response = await fetch(url, {
      method: 'POST',
      mode: 'cors',
      headers: { 'Content-Type': 'text/plain;charset=utf-8' },
      body: JSON.stringify(payload),
      redirect: 'follow'
    });

    if (!response.ok) throw new Error('HTTP ' + response.status);
    const result = await response.json();
    if (result.status !== 'ok') throw new Error(result.message || 'Server error');

    openModal();
  } catch (err) {
    console.error('Submit error:', err);
    showToast(I18N[currentLang]['err.network']);
  } finally {
    btn.classList.remove('is-loading');
    btn.disabled = false;
  }
});
