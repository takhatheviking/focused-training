const PHONE_RE = /^[\+\d][\d\s\-\(\)]{7,20}$/;

function validateField(field) {
  const input = field.querySelector('input, textarea, select');
  const errorEl = field.querySelector('.field__error');
  let valid = true;
  let errorKey = 'err.required';

  if (field.dataset.field === 'channel') {
    const checked = field.querySelector('input[type="radio"]:checked');
    valid = !!checked;
    errorKey = 'err.channel';
  } else if (input) {
    const value = input.value.trim();
    if (input.required && !value) {
      valid = false;
      errorKey = 'err.required';
    } else if (input.type === 'tel' && value && !PHONE_RE.test(value)) {
      valid = false;
      errorKey = 'err.phone';
    }
  }

  field.classList.toggle('field--invalid', !valid);
  if (errorEl && !valid) {
    errorEl.textContent = I18N[currentLang][errorKey];
  }
  return valid;
}

document.querySelectorAll('.field__input, .field__textarea, .field__select').forEach(input => {
  input.addEventListener('input', () => {
    const field = input.closest('.field');
    if (field && field.classList.contains('field--invalid')) {
      field.classList.remove('field--invalid');
    }
  });
});

document.querySelectorAll('input[type="radio"][name="channel"]').forEach(radio => {
  radio.addEventListener('change', () => {
    const field = radio.closest('.field');
    if (field) field.classList.remove('field--invalid');
  });
});

